      var p = Math.min(1, (ts - t0) / (i === cur ? 1 : TRAVEL)), e = ease(p);
      if (!vertical()) place(a.x + (b.x - a.x) * e, a.y + (b.y - a.y) * e);
      if (p < 1) { raf = requestAnimationFrame(step); }
      else { cur = i; setActive(i); timer = setTimeout(function () { goTo(i + 1); }, HOLD); }
    }
    raf = requestAnimationFrame(step);
  }

  function run() {
    if (started) return;
    started = true;
    s.classList.add("is-live");
    place(pts[0].x, pts[0].y);
    goTo(0);
  }

  /* hovering / focusing a stage pauses the tour and shows that stage */
  nodes.forEach(function (n, i) {
    n.addEventListener("mouseenter", function () { paused = true; setActive(i); if (!vertical()) place(pts[i].x, pts[i].y); cur = i; });
    n.addEventListener("focus", function () { paused = true; setActive(i); if (!vertical()) place(pts[i].x, pts[i].y); cur = i; });
  });
  path.addEventListener("mouseleave", function () { paused = false; });
  path.addEventListener("focusout", function () { paused = false; });

  /* ---- pointer parallax on the background lines ---- */
  if (window.matchMedia("(hover: hover)").matches) {
    var pr = 0;
    s.addEventListener("mousemove", function (ev) {
      if (pr) return;
      pr = requestAnimationFrame(function () {
        var r = s.getBoundingClientRect();
        s.style.setProperty("--px", ((ev.clientX - r.left) / r.width - 0.5).toFixed(3));
        s.style.setProperty("--py", ((ev.clientY - r.top) / r.height - 0.5).toFixed(3));
        pr = 0;
      });
    });

    /* ---- magnetic button ---- */
    var btn = s.querySelector(".cl-cta__btn"), wrap = s.querySelector(".cl-cta__action");
    if (btn && wrap) {
      wrap.addEventListener("mousemove", function (e) {
        var r = btn.getBoundingClientRect();
        var dx = e.clientX - (r.left + r.width / 2), dy = e.clientY - (r.top + r.height / 2);
        btn.style.transform = "translate(" + (dx * 0.12).toFixed(1) + "px," + (dy * 0.25).toFixed(1) + "px)";
      });
      wrap.addEventListener("mouseleave", function () { btn.style.transform = ""; });
      btn.style.transition = "transform 0.25s ease-out, box-shadow 0.35s ease";
    }
  }
})();
