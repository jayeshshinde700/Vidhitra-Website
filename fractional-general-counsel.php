  <script>
    // ==========================================================
    // ABOUT PAGE SUB-NAV — sticky pin under main header + scroll-spy
    // The "About Us" label only appears once .is-sticky is added
    // (handled purely via CSS, see .vd-page-subnav.is-sticky rule).
    // ==========================================================
    (function () {
      const subnav = document.getElementById('vdPageSubnav');
      const spacer = document.getElementById('vdPageSubnavSpacer');
      const tabsWrap = document.getElementById('vdPageSubnavTabs');
      if (!subnav || !tabsWrap) return;

      const tabs = Array.from(tabsWrap.querySelectorAll('a'));
      const sections = tabs
        .map((a) => document.querySelector(a.getAttribute('href')))
        .filter(Boolean);

      const stickyHeader = document.querySelector('.header-duplicate');

      let subnavTop = 0;
      let headerHeight = 0;
      let subnavHeight = subnav.offsetHeight;

      function measure() {
        const wasSticky = subnav.classList.contains('is-sticky');
        if (wasSticky) {
          subnav.classList.remove('is-sticky');
          spacer.classList.remove('is-active');
        }
        headerHeight = stickyHeader ? stickyHeader.offsetHeight : 0;
        subnavHeight = subnav.offsetHeight;
        subnavTop = subnav.getBoundingClientRect().top + window.scrollY;
        spacer.style.height = subnavHeight + 'px';
        if (wasSticky) {
          subnav.classList.add('is-sticky');
          spacer.classList.add('is-active');
        }
      }

      function onScroll() {
        if (window.scrollY >= subnavTop - headerHeight) {
          subnav.classList.add('is-sticky');
          subnav.style.top = headerHeight + 'px';
          spacer.classList.add('is-active');
        } else {
          subnav.classList.remove('is-sticky');
          subnav.style.top = '';
          spacer.classList.remove('is-active');
        }
      }

      measure();
      onScroll();

      window.addEventListener('load', () => { measure(); onScroll(); });
      window.addEventListener('resize', () => { measure(); onScroll(); });
      window.addEventListener('scroll', onScroll, { passive: true });

      tabs.forEach((tab) => {
        tab.addEventListener('click', function (e) {
          e.preventDefault();
          const target = document.querySelector(this.getAttribute('href'));
          if (!target) return;
          scrollToSection(target);
        });
      });

      // Extra breathing room under the pinned header + sub-nav (done in JS so normal scrolling has no gap)
      const EXTRA_GAP = window.innerWidth <= 991 ? 40 : 80;
      function scrollToSection(target) {
        measure();
        const offset = headerHeight + subnavHeight + EXTRA_GAP;
        const top = target.getBoundingClientRect().top + window.scrollY - offset;
        window.scrollTo({ top: Math.max(top, 0), behavior: 'smooth' });
      }

      // Header dropdown links (e.g. fractional-general-counsel.php#how-we-work) -> same offset
      document.querySelectorAll('a[href*="fractional-general-counsel.php#"]').forEach((a) => {
        a.addEventListener('click', function (e) {
          const id = this.getAttribute('href').split('#')[1];
          const target = id && document.getElementById(id);
          if (!target) return;
          e.preventDefault();
          history.replaceState(null, '', '#' + id);
          scrollToSection(target);
        });
      });

      // Arriving from another page with a #hash
      if (location.hash) {
        const t = document.getElementById(location.hash.slice(1));
        if (t) window.addEventListener('load', () => setTimeout(() => scrollToSection(t), 400));
      }

      if ('IntersectionObserver' in window && sections.length) {
        const spy = new IntersectionObserver(
          (entries) => {
            entries.forEach((entry) => {
              if (entry.isIntersecting) {
                const id = entry.target.getAttribute('id');
                tabs.forEach((t) =>
                  t.classList.toggle('active', t.getAttribute('href') === '#' + id)
                );
              }
            });
          },
          { rootMargin: '-35% 0px -55% 0px', threshold: 0 }
        );
        sections.forEach((sec) => spy.observe(sec));
      }
    })();
  </script>


