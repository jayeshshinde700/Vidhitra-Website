<script>
(function () {
  var root = document.querySelector('.va-page');
  if (!root) return;
  var reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var canHover = window.matchMedia('(hover: hover)').matches;

  /* 1. Split headings into words */
  root.querySelectorAll('.va-split').forEach(function (el) {
    var text = el.textContent.trim();
    el.setAttribute('aria-label', text);
    el.innerHTML = text.split(/\s+/).map(function (w, i) {
      return '<span class="va-w" aria-hidden="true"><span style="--i:' + i + '">' + w + '</span></span>';
    }).join(' ');
  });

  /* 2. Split perspective paragraphs into words for the reading fill */
  var scrubPs = root.querySelectorAll('.va-scrub-p');
  scrubPs.forEach(function (p) {
    p.innerHTML = p.textContent.trim().split(/\s+/).map(function (w) {
      return '<span class="va-sw">' + w + '</span>';
    }).join(' ');
  });

  /* 3. Counter */
  function runCount(el) {
    var target = parseInt(el.getAttribute('data-count'), 10);
    if (reduce) { el.textContent = target; return; }
    var start = null;
    function step(ts) {
      if (!start) start = ts;
      var p = Math.min((ts - start) / 1400, 1);
      el.textContent = Math.round(target * (1 - Math.pow(1 - p, 3)));
      if (p < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  }

  /* 4. Reveal on scroll (one-shot) */
  var reveal = root.querySelectorAll('.va-anim');
  function show(el) {
    el.classList.add('is-in');
    el.querySelectorAll('.va-count').forEach(runCount);
  }
  if (reduce || !('IntersectionObserver' in window)) {
    reveal.forEach(show);
  } else {
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (e.isIntersecting) { show(e.target); io.unobserve(e.target); }
      });
    }, { threshold: 0.18, rootMargin: '0px 0px -8% 0px' });
    reveal.forEach(function (el) { io.observe(el); });
  }

  /* 5. Scroll-linked effects */
  var parallax = root.querySelectorAll('[data-parallax]');
  var tl = document.getElementById('vaTimeline');
  var fill = tl ? tl.querySelector('.va-tl-fill') : null;
  var tlItems = tl ? tl.querySelectorAll('.va-tl-item') : [];
  var steps = root.querySelectorAll('#vaSteps .va-step');
  var mediaImgs = root.querySelectorAll('#vaHowMedia img');
  var howNum = document.getElementById('vaHowNum');
  var activeStep = 0;

  function update() {
    var vh = window.innerHeight;

    // perspective: words fill as the paragraph moves up the screen
    scrubPs.forEach(function (p) {
      var r = p.getBoundingClientRect();
      var prog = reduce ? 1 : Math.min(1, Math.max(0, (vh * 0.85 - r.top) / (vh * 0.5)));
      var words = p.querySelectorAll('.va-sw');
      var lit = Math.round(prog * words.length);
      words.forEach(function (w, i) { w.classList.toggle('is-on', i < lit); });
      p.style.setProperty('--p', prog);
    });

    // image parallax
    if (!reduce) {
      parallax.forEach(function (el) {
        var r = el.parentElement.getBoundingClientRect();
        var off = (r.top + r.height / 2 - vh / 2) * parseFloat(el.getAttribute('data-parallax'));
        el.style.transform = 'translate3d(0,' + off.toFixed(1) + 'px,0)';
      });
    }

    // how we work: step nearest the middle of the screen is active
    if (steps.length) {
      var best = 0, bestDist = Infinity;
      steps.forEach(function (s, i) {
        var r = s.getBoundingClientRect();
        var d = Math.abs(r.top + r.height / 2 - vh * 0.5);
        if (d < bestDist) { bestDist = d; best = i; }
      });
      if (best !== activeStep) {
        activeStep = best;
        steps.forEach(function (s, i) { s.classList.toggle('is-active', i === best); });
        mediaImgs.forEach(function (img, i) { img.classList.toggle('active', i === best); });
        if (howNum) howNum.textContent = '0' + (best + 1);
      }
    }

    // experience timeline
    if (tl && fill) {
      var tr = tl.getBoundingClientRect();
      var tprog = reduce ? 1 : Math.min(1, Math.max(0, (vh * 0.6 - tr.top) / tr.height));
      fill.style.transform = 'scaleY(' + tprog + ')';
      tlItems.forEach(function (it) {
        it.classList.toggle('is-active', reduce || it.getBoundingClientRect().top < vh * 0.62);
      });
    }
  }
  var ticking = false;
  function onScroll() {
    if (!ticking) { ticking = true; requestAnimationFrame(function () { ticking = false; update(); }); }
  }
  window.addEventListener('scroll', onScroll, { passive: true });
  window.addEventListener('resize', onScroll, { passive: true });
  window.addEventListener('load', update);
  update();

  /* 6. Feature card tilt + spotlight */
  if (!reduce && canHover) {
    root.querySelectorAll('.va-feature').forEach(function (card) {
      var inner = card.querySelector('.va-feature-inner');
      card.addEventListener('mousemove', function (e) {
        var r = card.getBoundingClientRect();
        var x = (e.clientX - r.left) / r.width;
        var y = (e.clientY - r.top) / r.height;
        inner.style.setProperty('--ry', ((x - 0.5) * 10) + 'deg');
        inner.style.setProperty('--rx', ((0.5 - y) * 10) + 'deg');
        inner.style.setProperty('--mx', (x * 100) + '%');
        inner.style.setProperty('--my', (y * 100) + '%');
      });
      card.addEventListener('mouseleave', function () {
        inner.style.setProperty('--rx', '0deg');
        inner.style.setProperty('--ry', '0deg');
      });
    });
  }

  /* 7. Leadership "Read full profile" */
  root.querySelectorAll('.va-toggle').forEach(function (btn) {
    btn.addEventListener('click', function () {
      var card = btn.closest('.va-leader');
      var more = document.getElementById(btn.getAttribute('aria-controls'));
      var open = card.classList.toggle('is-open');
      more.style.maxHeight = open ? more.scrollHeight + 'px' : '0px';
      btn.setAttribute('aria-expanded', open);
      btn.querySelector('span').textContent = open ? 'Show less' : 'Read full profile';
      setTimeout(function () {
        window.dispatchEvent(new Event('resize'));        // lets the sub-nav re-measure
        if (window.ScrollTrigger) ScrollTrigger.refresh();
      }, 750);
    });
  });

  /* 8. Star field */
  var stars = document.getElementById('vaStars');
  if (stars) {
    for (var i = 0; i < 70; i++) {
      var s = document.createElement('span');
      var size = Math.random() * 3 + 1.5;
      s.className = 'va-star';
      s.style.cssText = 'left:' + (Math.random() * 100) + '%;top:' + (Math.random() * 100) +
        '%;width:' + size + 'px;height:' + size + 'px;animation-delay:' + (Math.random() * 4).toFixed(2) + 's';
      stars.appendChild(s);
    }
  }

  /* 9. Magnetic CTA button */
  var magnet = document.getElementById('vaMagnet');
  if (magnet && !reduce && canHover) {
