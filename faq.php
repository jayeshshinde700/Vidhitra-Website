(function () {
  var secs = document.querySelectorAll('.vfq');
  if (!secs.length) return;
  if ('IntersectionObserver' in window) {
    var io = new IntersectionObserver(function (es) {
      es.forEach(function (e) {
        if (e.isIntersecting) {
          /* both sections start together so the two halves of the Q always line up */
          secs.forEach(function (s) { s.classList.add('is-in'); });
          io.disconnect();
        }
      });
    }, { threshold: 0.12 });
    secs.forEach(function (s) { io.observe(s); });
  } else {
    secs.forEach(function (s) { s.classList.add('is-in'); });
  }

  document.querySelectorAll('.vfq__list').forEach(function (list) {
   var items = list.querySelectorAll('.vfq__item');
   items.forEach(function (it) {
    it.querySelector('.vfq__q').addEventListener('click', function () {
      var open = it.classList.contains('is-open');
      items.forEach(function (x) {
        x.classList.remove('is-open');
        x.querySelector('.vfq__q').setAttribute('aria-expanded', 'false');
      });
      if (!open) { it.classList.add('is-open'); this.setAttribute('aria-expanded', 'true'); }
    });
   });
  });
})();
